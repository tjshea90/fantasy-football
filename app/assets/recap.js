/* recap.js — the week in one card, and a season schedule generator.
 * ES2018 only. NO NETWORK except the optional one-paragraph write-up.
 */
(function (root) {
  'use strict';

  function r1(x) { return Math.round(x * 10) / 10; }

  /* ---- the recap ---------------------------------------------------------
   * Everything here is computed from scored weeks. Nothing is estimated and
   * nothing is fetched: if a week is not final, there is no recap, rather than
   * a recap of a half-played week that reads like a result. */
  function build(week) {
    if (!root.Store.weekIsScored(week)) return null;
    var S = root.Store.get(), teams = S.teams, i;
    var scores = [];
    teams.forEach(function (t) {
      scores.push({ id: t.id, name: t.name, pts: root.Store.teamWeekPoints(week, t.id).total });
    });
    scores.sort(function (a, b) { return b.pts - a.pts; });
    var high = scores[0], low = scores[scores.length - 1];

    /* matchups: closest and most lopsided */
    var mus = root.Store.getMatchups(week), games = [];
    for (i = 0; i < mus.length; i++) {
      var a = mus[i][0], b = mus[i][1];
      var pa = root.Store.teamWeekPoints(week, a).total;
      var pb = root.Store.teamWeekPoints(week, b).total;
      games.push({ a: a, b: b, pa: pa, pb: pb, margin: Math.abs(pa - pb),
                   winner: pa >= pb ? a : b, loser: pa >= pb ? b : a,
                   winPts: Math.max(pa, pb), losePts: Math.min(pa, pb) });
    }
    games.sort(function (x, y) { return x.margin - y.margin; });
    var closest = games.length ? games[0] : null;
    var blowout = games.length ? games[games.length - 1] : null;

    /* the best individual week in the whole league, from the book — which
       covers players nobody rosters as well, so "the best week in football"
       is honest rather than "the best week among our 170" */
    var book = root.Store.bookWeek(week), bestP = null, k;
    for (k in book) {
      if (!Object.prototype.hasOwnProperty.call(book, k)) continue;
      if (!bestP || book[k].p > bestP.p) bestP = { key: k, n: book[k].n, t: book[k].t, p: book[k].p };
    }

    /* the best and worst STARTER in this league, and the biggest bust
       measured against that player's own season average — the only baseline
       the app can defend without having stored last week's projection */
    var starters = [], busts = [];
    var keys = root.Store.slotKeys();   /* identical for every team — hoisted */
    teams.forEach(function (t) {
      var lineup = root.Store.getLineup(week, t.id) || {};
      keys.forEach(function (kk) {
        var pid = lineup[kk.key];
        if (!pid) return;
        var rec = root.Store.playerById(pid);
        if (!rec) return;
        var pts = root.Store.playerPoints(week, pid);
        starters.push({ team: t.name, name: rec.player.name, pos: rec.player.pos, pts: pts });
        /* his own average over the other scored weeks */
        var sum = 0, n = 0, w;
        for (w = 1; w <= S.league.regularSeasonWeeks; w++) {
          if (w === week || !root.Store.weekIsScored(w)) continue;
          var l = root.Store.lineFor(w, pid);
          if (l && l.played) { sum += root.Scoring.score(l).total; n++; }
        }
        if (n >= 2) {
          var avg = sum / n;
          if (avg >= 8) busts.push({ team: t.name, name: rec.player.name, pts: pts,
                                     avg: avg, short: avg - pts });
        }
      });
    });
    starters.sort(function (x, y) { return y.pts - x.pts; });
    busts.sort(function (x, y) { return y.short - x.short; });

    /* who left the most on the bench */
    var regrets = [];
    teams.forEach(function (t) {
      var rg = root.Sim ? root.Sim.regret(week, t.id) : null;
      if (rg) regrets.push({ name: t.name, id: t.id, lost: rg.lost, actual: rg.actual });
    });
    regrets.sort(function (x, y) { return y.lost - x.lost; });

    return {
      week: week, scores: scores, high: high, low: low, games: games,
      closest: closest, blowout: blowout, bestPlayer: bestP,
      topStarter: starters.length ? starters[0] : null,
      bust: busts.length ? busts[0] : null,
      regret: regrets.length ? regrets[0] : null,
      myRegret: regrets.filter(function (x) { return x.id === S.league.me; })[0] || null
    };
  }

  /* Plain text, ready to paste into the league chat. Deliberately not
     generated by a model: it is facts, and facts do not need writing. */
  /* `prebuilt` lets a caller that has already run build(week) avoid running
     it a second time. build() is not cheap: it calls teamWeekPoints for all
     ten teams plus twice per matchup, then walks fourteen weeks per starter —
     roughly 1,540 score() calls. The recap card had it doing that twice. */
  function text(week, prebuilt) {
    var r = prebuilt || build(week);
    if (!r) return '';
    var L = [];
    L.push('WEEK ' + week + ' — ' + root.Store.get().league.name);
    L.push('');
    L.push('High score: ' + r.high.name + ' ' + r1(r.high.pts));
    L.push('Low score:  ' + r.low.name + ' ' + r1(r.low.pts));
    if (r.closest) {
      L.push('Closest:    ' + nm(r.closest.winner) + ' ' + r1(r.closest.winPts) + ' d. ' +
             nm(r.closest.loser) + ' ' + r1(r.closest.losePts) +
             ' (' + r1(r.closest.margin) + ')');
    }
    if (r.blowout && r.games.length > 1) {
      L.push('Biggest:    ' + nm(r.blowout.winner) + ' ' + r1(r.blowout.winPts) + ' d. ' +
             nm(r.blowout.loser) + ' ' + r1(r.blowout.losePts) +
             ' (' + r1(r.blowout.margin) + ')');
    }
    L.push('');
    if (r.topStarter) {
      L.push('Best starter: ' + r.topStarter.name + ' (' + r.topStarter.pos + ', ' +
             r.topStarter.team + ') ' + r1(r.topStarter.pts));
    }
    if (r.bestPlayer) {
      L.push('Best in the NFL this week: ' + r.bestPlayer.n + ' ' + r1(r.bestPlayer.p));
    }
    if (r.bust) {
      L.push('Biggest letdown: ' + r.bust.name + ' (' + r.bust.team + ') ' +
             r1(r.bust.pts) + ' against a ' + r1(r.bust.avg) + ' average');
    }
    if (r.regret && r.regret.lost > 0.05) {
      L.push('Most left on the bench: ' + r.regret.name + ' ' + r1(r.regret.lost));
    }
    L.push('');
    L.push('Every number in this league\'s scoring.');
    return L.join('\n');
  }
  function nm(id) { var t = root.Store.team(id); return t ? t.name : id; }

  /* ---- the schedule ------------------------------------------------------
   * Circle method. With ten teams a full round robin is nine weeks, so a
   * fourteen-week season is one full round plus the first five rounds again
   * with home and away swapped. Weeks that are already scored are NEVER
   * overwritten — a generator that erased results would be a disaster with a
   * friendly name. */
  function generateSchedule(opts) {
    var S = root.Store.get();
    var ids = S.teams.map(function (t) { return t.id; });
    var reg = S.league.regularSeasonWeeks;
    if (ids.length < 2) return { weeks: 0, skipped: [], error: 'not enough teams' };
    if (ids.length % 2) ids.push(null);              /* bye slot */
    var n = ids.length, rounds = n - 1, half = n / 2;
    var arr = ids.slice(), out = [], w, i;
    for (w = 0; w < reg; w++) {
      var round = w % rounds;
      /* circle method: team 0 is fixed, the rest rotate. Rebuilt from the
         original order every week, so a fourteen-week season cannot drift. */
      var rest = ids.slice(1), cut = rest.length - (round % rest.length);
      var cur = [ids[0]].concat(rest.slice(cut)).concat(rest.slice(0, cut));
      var pairs = [];
      for (i = 0; i < half; i++) {
        var a = cur[i], b = cur[n - 1 - i];
        if (a === null || b === null) continue;
        /* swap the order on the second pass so nobody is always listed first */
        pairs.push(w >= rounds ? [b, a] : [a, b]);
      }
      out.push(pairs);
    }
    var skipped = [], written = 0;
    for (w = 1; w <= reg; w++) {
      if (root.Store.weekIsScored(w) && !(opts && opts.force)) { skipped.push(w); continue; }
      root.Store.setMatchups(w, out[w - 1]);
      written++;
    }
    return { weeks: written, skipped: skipped, total: reg, error: '' };
  }

  root.Recap = { build: build, text: text, generateSchedule: generateSchedule };
  if (typeof module !== 'undefined' && module.exports) module.exports = root.Recap;
})(typeof window !== 'undefined' ? window : this);
